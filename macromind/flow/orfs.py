"""ORFS integration: design specs, placer switch, generated config.mk, make/openroad commands.

Mechanism (see docs/harness.md): ORFS's own ``MACRO_PLACEMENT_TCL`` variable.
In this ORFS version (``scripts/macro_place_util.tcl``) stage
``2_2_floorplan_macro`` sources ``$MACRO_PLACEMENT_TCL`` *instead of* running
``rtl_macro_placer`` and then still runs the channel blockages and writes the
stage ODB. We point it at :data:`HOOK_TCL`, which dumps the floorplan DEF,
runs ``python -m macromind.flow.place`` in the venv and sources the resulting
``place_macro`` commands. No ORFS file is patched.

The user-facing switch is ``MACRO_PLACER=macromind-<method>|rtlmp`` in the
generated wrapper ``config.mk``, which ``include``\\s the stock design config.
"""

from __future__ import annotations

import hashlib
import json
import os
import shlex
import subprocess
import sys
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
HOOK_TCL = Path(__file__).resolve().parent / "orfs_hook.tcl"
MACROMIND_METHODS = ("random", "grid", "sa", "rl")
PLACERS = ("rtlmp",) + tuple(f"macromind-{m}" for m in MACROMIND_METHODS)

#: harness ``--stop-after`` -> ORFS make target
STOP_TARGETS = {"floorplan": "floorplan", "place": "place", "cts": "cts", "grt": "grt", "route": "route",
                "finish": "finish"}


def flow_home() -> Path:
    return Path(os.environ.get("FLOW_HOME") or REPO_ROOT / "tools/ORFS/flow")


def orfs_version() -> str:
    """ORFS install tag from the ``tools/ORFS/.installed-<tag>`` stamp."""
    stamps = sorted((flow_home().parent).glob(".installed-*"))
    return stamps[-1].name[len(".installed-"):] if stamps else "unknown"


@dataclass(frozen=True)
class DesignSpec:
    platform: str
    design: str

    @classmethod
    def parse(cls, s: str) -> "DesignSpec":
        if "/" in s:
            p, d = s.split("/", 1)
        else:
            p, d = "nangate45", s
        if not p or not d or "/" in d:
            raise ValueError(f"bad design spec {s!r}; use <platform>/<design>")
        return cls(p, d)

    def __str__(self) -> str:
        return f"{self.platform}/{self.design}"

    @property
    def tag(self) -> str:
        return f"{self.platform}_{self.design}"

    def config_path(self, home: Path | None = None) -> Path:
        return (home or flow_home()) / "designs" / self.platform / self.design / "config.mk"


@dataclass(frozen=True)
class PlacerSpec:
    kind: str  # "rtlmp" | "macromind"
    method: str | None = None

    @classmethod
    def parse(cls, s: str) -> "PlacerSpec":
        s = s.strip().lower()
        if s in ("rtlmp", "default", "orfs"):
            return cls("rtlmp")
        m = s[len("macromind-"):] if s.startswith("macromind-") else s
        if m in MACROMIND_METHODS:
            return cls("macromind", m)
        raise ValueError(f"unknown placer {s!r}; choose from {PLACERS}")

    @property
    def name(self) -> str:
        return "rtlmp" if self.kind == "rtlmp" else f"macromind-{self.method}"

    def __str__(self) -> str:
        return self.name


def _mk_escape(v: str) -> str:
    return str(v).replace("$", "$$")


def wrapper_config(design: DesignSpec, placer: PlacerSpec, seed: int, out_dir: str | Path, *, python: str | None = None,
                   budget: int | None = None, rl_ckpt: str | None = None, extra: dict | None = None,
                   home: Path | None = None) -> str:
    """Text of a config.mk that includes the stock design config and selects the macro placer."""
    cfg = design.config_path(home)
    lines = [
        "# Generated by macromind.flow.orfs -- do not edit",
        f"include {cfg}",
        "",
        f"export MACRO_PLACER = {placer.name}",
    ]
    if placer.kind == "macromind":
        lines += [
            f"export MACRO_PLACEMENT_TCL = {HOOK_TCL}",
            "export MACRO_PLACEMENT =",
            f"export MACROMIND_METHOD = {placer.method}",
            f"export MACROMIND_SEED = {int(seed)}",
            f"export MACROMIND_PYTHON = {python or sys.executable}",
            f"export MACROMIND_ROOT = {REPO_ROOT}",
            f"export MACROMIND_OUT_DIR = {Path(out_dir).resolve()}",
        ]
        if budget is not None:
            lines.append(f"export MACROMIND_BUDGET = {int(budget)}")
        if placer.method == "rl":
            ck = rl_ckpt or os.environ.get("MACROMIND_RL_CKPT") or str(REPO_ROOT / "runs/rl-v1/policy.pt")
            lines.append(f"export MACROMIND_RL_CKPT = {Path(ck).resolve()}")
    for k, v in sorted((extra or {}).items()):
        lines.append(f"export {k} = {_mk_escape(v)}")
    return "\n".join(lines) + "\n"


@lru_cache(maxsize=1)
def tool_env() -> dict[str, str]:
    """Environment after ``source scripts/env.sh`` (PATH, FLOW_HOME, LD_LIBRARY_PATH ...)."""
    env_sh = REPO_ROOT / "scripts/env.sh"
    out = subprocess.run(["bash", "-c", f"source {shlex.quote(str(env_sh))} >/dev/null && env -0"], capture_output=True,
                         check=True, env={k: v for k, v in os.environ.items() if k != "PYTHONHOME"})
    env = {}
    for item in out.stdout.split(b"\0"):
        if b"=" in item:
            k, v = item.split(b"=", 1)
            env[k.decode()] = v.decode()
    env.pop("PYTHONHOME", None)
    # ORFS's helper scripts run `python3` and need PyYAML from the system
    # interpreter: keep the MacroMind venv off PATH for make/openroad.
    venv = env.pop("VIRTUAL_ENV", None) or os.environ.get("VIRTUAL_ENV")
    exe_dir = str(Path(sys.executable).parent)
    env["PATH"] = os.pathsep.join(p for p in env.get("PATH", "").split(os.pathsep)
                                  if p and p != exe_dir and not (venv and p.startswith(venv)))
    return env


def make_cmd(config: str | Path, work_home: str | Path, target: str | list[str], *, num_cores: int = 2,
             variant: str = "base", extra: list[str] | None = None) -> list[str]:
    targets = [target] if isinstance(target, str) else list(target)
    return ["make", "-C", str(flow_home()), f"DESIGN_CONFIG={config}", f"WORK_HOME={work_home}",
            f"FLOW_VARIANT={variant}", f"NUM_CORES={num_cores}", *(extra or []), *targets]


def print_vars(config: str | Path, work_home: str | Path, names: list[str]) -> dict[str, str]:
    """Values of ORFS make variables (``make print-<VAR>``)."""
    import fcntl

    cmd = make_cmd(config, work_home, [f"print-{n}" for n in names]) + ["-s"]
    # ORFS's print-% rule goes through one fixed temp file (/tmp/print_tmp$), so
    # concurrent prints race: serialise them across threads and processes.
    with open("/tmp/macromind_orfs_print.lock", "w") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        out = subprocess.run(cmd, capture_output=True, text=True, env=tool_env(), timeout=120)
    vals = {}
    for line in out.stdout.splitlines():
        if " = " in line:
            k, v = line.split(" = ", 1)
            if k.strip() in names:
                vals[k.strip()] = v.strip()
    missing = [n for n in names if n not in vals]
    if missing:
        raise RuntimeError(f"make print failed for {missing}: {out.stderr[-500:]}")
    return vals


def export_def_tcl(odb: str | Path, def_out: str | Path) -> str:
    return f"read_db {{{odb}}}\nwrite_def {{{def_out}}}\n"


def file_digest(paths: list[Path]) -> str:
    h = hashlib.sha256()
    for p in sorted(paths):
        h.update(str(p.relative_to(REPO_ROOT) if p.is_relative_to(REPO_ROOT) else p).encode())
        h.update(p.read_bytes())
    return h.hexdigest()


@lru_cache(maxsize=1)
def code_version() -> str:
    """Content hash of the MacroMind code that can change a placement (.py outside harness/report/predict + the hook)."""
    pkg = REPO_ROOT / "macromind"
    skip = {"__pycache__", "harness", "report", "predict"}
    files = [p for p in pkg.rglob("*.py") if not skip.intersection(p.relative_to(pkg).parts)] + [HOOK_TCL]
    return file_digest(files)[:16]


def design_digest(design: DesignSpec) -> str:
    """Hash of the stock design directory's config + constraint files (not the RTL tree)."""
    d = design.config_path().parent
    files = [p for p in d.iterdir() if p.is_file() and p.suffix in (".mk", ".sdc", ".tcl", ".v", ".lef", ".lib", ".cfg")]
    return file_digest(files)[:16]


def dumps_canonical(obj) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), default=str)
